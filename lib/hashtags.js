/**
 * Extract all hashtags from any text block
 */
export function parseHashtagsFromText(text = '') {
  if (!text) return [];
  const regex = /#[A-Za-z0-9_]+/g;
  const matches = text.match(regex);
  return matches ? Array.from(new Set(matches)) : [];
}
