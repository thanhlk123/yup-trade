/**
 * Helper to find definition for a given tag
 */
export function getHashtagInfo(tagString, customTags = []) {
  if (!tagString) return null;
  const cleanTag = tagString.trim().toLowerCase();

  // Check custom tags first
  if (customTags && customTags.length > 0) {
    const customFound = customTags.find(item => item.tag.toLowerCase() === cleanTag);
    if (customFound) return customFound;
  }

  for (const catKey in OFFICIAL_HASHTAGS) {
    const found = OFFICIAL_HASHTAGS[catKey].find(
      item => item.tag.toLowerCase() === cleanTag
    );
    if (found) return found;
  }

  // Fallback for partial tag matches (e.g. #DCA, #LHRetest)
  for (const catKey in OFFICIAL_HASHTAGS) {
    const found = OFFICIAL_HASHTAGS[catKey].find(
      item => item.tag.toLowerCase().includes(cleanTag.replace('#', ''))
    );
    if (found) return found;
  }

  return null;
}

